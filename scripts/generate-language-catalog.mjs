import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = await readFile(path.join(root, "contracts/languages.v1.json"), "utf8");
const data = JSON.parse(source);
if (data.catalogVersion !== 1 || data.generationPairs.length !== 10 ||
    new Set(data.generationPairs.map(p => `${p.targetLanguage}/${p.supportLanguage}`)).size !== 10) {
  throw new Error("Invalid language catalog");
}
const outputs = new Map([
  ["三句/LanguageCatalogResource.swift", `// Generated by scripts/generate-language-catalog.mjs. Do not edit.\nimport Foundation\n\nnonisolated enum LanguageCatalogResource {\n    static let json = #\"\"\"\n${source.trim()}\n\"\"\"#\n}\n`],
  ["supabase/functions/_shared/languages/catalog.ts", `// Generated by scripts/generate-language-catalog.mjs. Do not edit.\nexport const languageCatalog = ${JSON.stringify(data, null, 2)} as const\n`],
]);
for (const [relative, contents] of outputs) {
  const file = path.join(root, relative);
  if (process.argv.includes("--check")) {
    if (await readFile(file, "utf8") !== contents) throw new Error(`Stale generated catalog: ${relative}`);
  } else {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, contents);
  }
}
console.log(process.argv.includes("--check") ? "Language catalog resources match" : "Language catalog generated");
